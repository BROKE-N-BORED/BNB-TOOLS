#!/usr/bin/env python3
"""T9 brand-scrub-rename — grep-driven whole-tree substitution.

Pairs with skill S30 (brand scrub + rename-with-migration). From the
Forge no-brands scrub (235 substitutions, 28 files) and the
Goldfish→GoFish rename (351 substitutions, 14 files, migrations so
user state carried over).

Flow:
  1. Walk the tree (skipping .git, __pycache__, .venv, .forge, and
     binary files — detected by NUL byte, not extension).
  2. Report every file + match count BEFORE changing anything.
     DRY-RUN IS THE DEFAULT; --apply writes.
  3. After --apply, run a case-insensitive whole-tree grep for the old
     string to catch stragglers (the scrub that caught a missed file
     in the Forge run).
  4. With --key-renames (JSON mapping old_key -> new_key), generate
     migration scaffolding: a JSON mapping file + a small migrate.py
     snippet that renames keys in a state dict, so existing user data
     (plans, toggles, skill on/off) survives the rename.

Substitution is literal (not regex) by default; --regex enables
regular expressions. Case-sensitive by default; --ignore-case matches
any case (replacement keeps the given new string verbatim).

Stdlib only. Python 3.8+.
"""
import argparse
import json
import os
import re
import sys

DEFAULT_EXCLUDES = {".git", "__pycache__", ".venv", ".forge",
                    "node_modules", ".tox", ".mypy_cache"}
BINARY_EXTS = {".png", ".jpg", ".jpeg", ".gif", ".ico", ".pdf", ".zip",
               ".gz", ".woff", ".woff2", ".ttf", ".otf", ".mp3", ".mp4",
               ".sqlite", ".db"}


def is_binary(path):
    _, ext = os.path.splitext(path)
    if ext.lower() in BINARY_EXTS:
        return True
    try:
        with open(path, "rb") as f:
            return b"\x00" in f.read(8192)
    except OSError:
        return True


def walk_files(tree, extra_excludes):
    excludes = DEFAULT_EXCLUDES | set(extra_excludes)
    for dirpath, dirnames, filenames in os.walk(tree):
        dirnames[:] = [d for d in dirnames if d not in excludes]
        for name in sorted(filenames):
            yield os.path.join(dirpath, name)


def scan(tree, pattern, extra_excludes):
    """Return {relpath: count} for files containing the pattern."""
    hits = {}
    for path in walk_files(tree, extra_excludes):
        if is_binary(path):
            continue
        try:
            with open(path, encoding="utf-8", errors="strict") as f:
                text = f.read()
        except (UnicodeDecodeError, OSError):
            continue
        n = len(pattern.findall(text))
        if n:
            hits[os.path.relpath(path, tree)] = n
    return hits


def apply_substitution(tree, pattern, new, hits, extra_excludes):
    changed = {}
    for rel in hits:
        path = os.path.join(tree, rel)
        with open(path, encoding="utf-8") as f:
            text = f.read()
        new_text, n = pattern.subn(new, text)
        if n:
            with open(path, "w", encoding="utf-8") as f:
                f.write(new_text)
            changed[rel] = n
    return changed


def make_migration(key_renames, out_path):
    mapping = dict(key_renames)
    snippet = '''"""State-key migration scaffold — generated by bnb-tools T9.

Rename the keys listed in the mapping so existing user state (plans,
toggles, skill on/off) survives the rename. Call migrate_state() on
the loaded state dict before use; it renames keys in place and returns
the dict. Keys not in the mapping pass through untouched.
"""
MAPPING = %s


def migrate_state(state):
    for old, new in MAPPING.items():
        if old in state and new not in state:
            state[new] = state.pop(old)
        elif old in state:
            # Both keys present: the new key wins; drop the stale old one.
            state.pop(old)
    return state
''' % json.dumps(mapping, indent=4, sort_keys=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(snippet)
    return out_path


def main(argv=None):
    ap = argparse.ArgumentParser(
        prog="scrub.py",
        description="Grep-driven whole-tree substitution with straggler "
                    "catch and migration scaffolding.")
    ap.add_argument("old", help="string to replace (or remove)")
    ap.add_argument("new", nargs="?", default=None,
                    help="replacement string (omit with --remove)")
    ap.add_argument("--tree", required=True, help="tree to scrub")
    ap.add_argument("--remove", action="store_true",
                    help="delete the old string instead of replacing it")
    ap.add_argument("--regex", action="store_true",
                    help="treat OLD as a regular expression")
    ap.add_argument("--ignore-case", action="store_true",
                    help="case-insensitive matching")
    ap.add_argument("--apply", action="store_true",
                    help="write changes (default is dry-run)")
    ap.add_argument("--exclude", action="append", default=[],
                    help="extra directory name to skip (repeatable)")
    ap.add_argument("--key-renames", default=None,
                    help="JSON file mapping old state key -> new state key")
    ap.add_argument("--migration-out", default="migrate.py",
                    help="where to write the migration snippet "
                         "(default migrate.py, only with --key-renames)")
    ap.add_argument("--mapping-out", default="key-mapping.json",
                    help="where to write the JSON key mapping "
                         "(default key-mapping.json)")
    args = ap.parse_args(argv)
    if args.remove and args.new is not None:
        ap.error("--remove and a replacement string are mutually exclusive")
    if not args.remove and args.new is None:
        ap.error("give a replacement string, or --remove")
    new = "" if args.remove else args.new
    flags = re.IGNORECASE if args.ignore_case else 0
    pat_text = args.old if args.regex else re.escape(args.old)
    pattern = re.compile(pat_text, flags)

    tree = os.path.abspath(args.tree)
    if not os.path.isdir(tree):
        raise SystemExit(f"error: tree not found: {tree}")

    hits = scan(tree, pattern, args.exclude)
    total = sum(hits.values())
    print(f"scan: {total} occurrence(s) in {len(hits)} file(s)")
    for rel in sorted(hits):
        print(f"  {rel}: {hits[rel]}")
    if not hits:
        print("nothing to change")
        return 0
    if not args.apply:
        print("DRY RUN — no files changed. Re-run with --apply to write.")
        return 0

    changed = apply_substitution(tree, pattern, new, hits, args.exclude)
    print(f"applied: {sum(changed.values())} substitution(s) in "
          f"{len(changed)} file(s)")

    # Straggler catch: case-insensitive whole-tree grep for the old string.
    straggler_pat = re.compile(re.escape(args.old), re.IGNORECASE)
    stragglers = scan(tree, straggler_pat, args.exclude)
    if stragglers:
        print(f"STRAGGLERS: {sum(stragglers.values())} occurrence(s) "
              f"remain in {len(stragglers)} file(s):")
        for rel in sorted(stragglers):
            print(f"  {rel}: {stragglers[rel]}")
        return 1
    print("straggler grep: clean — no occurrence of the old string remains")

    if args.key_renames:
        with open(args.key_renames, encoding="utf-8") as f:
            renames = json.load(f)
        with open(args.mapping_out, "w", encoding="utf-8") as f:
            json.dump(renames, f, indent=2, sort_keys=True)
        make_migration(renames, args.migration_out)
        print(f"migration: {args.mapping_out} + {args.migration_out} "
              f"({len(renames)} key rename(s))")
    return 0


if __name__ == "__main__":
    sys.exit(main())
